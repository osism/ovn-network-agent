// sbMonitorTables and nbMonitorTables project each monitored table down to the
// columns the agent actually consumes.
//
// The projection is mandatory, not an optimisation. A generated model carries
// every column of its table, and an unprojected WithTable monitors all of them:
// Chassis.nb_cfg is bumped by ovn-northd on every processing round, so
// monitoring it would fire a cache event — and therefore a state refresh — on a
// cadence that has nothing to do with the agent's inputs, storming the debounce
// loop on an otherwise idle cluster. Listing the columns explicitly also keeps
// the monitor honest: the set below is exactly what refreshState, the cache
// consistency guard (see the *CheckColumns in ovn_cache.go) and the gateway
// writers read.
func sbMonitorTables() []client.MonitorOption {
	pb := SBPortBinding{}
	ch := SBChassis{}
	return []client.MonitorOption{
		client.WithTable(&pb,
			&pb.LogicalPort,  // chassisredirect / patch / localnet port name
			&pb.Type,         // row kind: chassisredirect, patch, localnet
			&pb.Chassis,      // which chassis owns a chassisredirect port
			&pb.Datapath,     // localnet ↔ patch join key
			&pb.Tag,          // VLAN tag of a localnet segment
			&pb.Options,      // distributed-port, peer, network_name
			&pb.ExternalIDs,  // neutron:device_owner (router-gateway filter)
			&pb.NatAddresses, // SB-side SNAT addresses of a gateway port
		),
		client.WithTable(&ch,
			&ch.Name,     // chassis reference form used by Port_Binding.chassis
			&ch.Hostname, // maps a chassis to this host
			// Deliberately NOT nb_cfg: northd bumps it every round.
		),
	}
}

func nbMonitorTables() []client.MonitorOption {
	nat := NBNAT{}
	lr := NBLogicalRouter{}
	lrp := NBLogicalRouterPort{}
	lrsr := NBLogicalRouterStaticRoute{}
	smb := NBStaticMACBinding{}
	gwc := NBGatewayChassis{}
	return []client.MonitorOption{
		client.WithTable(&nat,
			&nat.Type,       // dnat_and_snat vs snat
			&nat.ExternalIP, // the FIP / SNAT address itself
		),
		client.WithTable(&lr,
			&lr.Name,
			&lr.Ports,        // → Logical_Router_Port
			&lr.Nat,          // → NAT
			&lr.StaticRoutes, // → Logical_Router_Static_Route (managed routes)
		),
		client.WithTable(&lrp,
			&lrp.Name,
			&lrp.MAC,            // hairpin dl_dst
			&lrp.Networks,       // discovered provider networks
			&lrp.GatewayChassis, // → Gateway_Chassis (HA group join)
		),
		client.WithTable(&lrsr,
			&lrsr.IPPrefix,
			&lrsr.Nexthop,
			&lrsr.OutputPort,
			&lrsr.ExternalIDs, // agent-managed marker + takeover marker
		),
		client.WithTable(&smb,
			&smb.LogicalPort,
			&smb.IP,
			&smb.MAC,
		),
		client.WithTable(&gwc,
			&gwc.Name,
			&gwc.ChassisName,
			&gwc.Priority, // the anti-flapping lead
		),
	}
}

func ovsdbEndpoints(remote string) []string {
	parts := strings.Split(remote, ",")
	var endpoints []string
	for _, p := range parts {
		p = strings.TrimSpace(p)
		if p != "" {
			endpoints = append(endpoints, p)
		}
	}
	return endpoints
}

// uniqueNetworks deduplicates and sorts a list of *net.IPNet by string representation.
func uniqueNetworks(nets []*net.IPNet) []*net.IPNet {
	seen := make(map[string]bool, len(nets))
	var result []*net.IPNet
	for _, n := range nets {
		key := n.String()
		if !seen[key] {
			seen[key] = true
			result = append(result, n)
		}
	}
	sort.Slice(result, func(i, j int) bool {
		return result[i].String() < result[j].String()
	})
	return result
}

// parseNatAddressIPs extracts IP addresses from an OVN NatAddresses entry.
// Format: "MAC IP1 [IP2 ...] [is_chassis_resident("port")]"
func parseNatAddressIPs(natAddr string) []string {
	fields := strings.Fields(natAddr)
	if len(fields) < 2 {
		return nil
	}
	var ips []string
	for _, f := range fields[1:] {
		if strings.HasPrefix(f, "is_chassis_resident") {
			break
		}
		if net.ParseIP(f) != nil {
			ips = append(ips, f)
		}
	}
	return ips
}

func getHostname() (string, error) {
	h, err := os.Hostname()
	if err != nil {
		return "", err
	}
	return shortHostname(h), nil
}

// shortHostname returns the leading DNS label of a hostname. SB Chassis
// hostnames are often FQDNs while the agent's own hostname (getHostname) is
// domain-stripped, so any comparison between the two must first reduce both to
// this label. Casing is preserved: both sides ultimately derive from the same
// OS hostname, so a naive strip keeps them comparable while hostnamesEqual
// still guards against incidental case drift.
func shortHostname(h string) string {
	if idx := strings.IndexByte(h, '.'); idx != -1 {
		h = h[:idx]
	}
	return h
}

// hostnamesEqual reports whether two chassis hostnames name the same host. It
// compares only the leading DNS label, case-insensitively, so an FQDN SB
// hostname matches the agent's domain-stripped local hostname regardless of
// case. This is the single seam for chassis-hostname matching.
func hostnamesEqual(a, b string) bool {
	return strings.EqualFold(shortHostname(a), shortHostname(b))
}
