// =============================================================================
// OVN database models
// =============================================================================
//
// The models are generated by libovsdb's modelgen from the OVN schemas checked
// in under schemas/ (see docs/contributing/ovsdb-models.md). They are aliased —
// not wrapped — so the whole agent keeps using the short SB*/NB* names while the
// column definitions themselves are regenerated rather than hand-maintained:
// picking up a new OVN column is `make models-gen`, not a hand-edited struct
// that silently disagrees with the server.
//
// Only the eight tables below are registered in the client database models, so
// connect-time schema validation stays scoped to what the agent actually reads
// and writes. The monitors additionally project explicit column lists — see
// Connect — because a generated model carries every column of its table, and
// monitoring a hot one (Chassis.nb_cfg changes on every northd round) would
// storm the debounce loop.

type (
	// OVN Southbound
	SBPortBinding = sbdb.PortBinding
	SBChassis     = sbdb.Chassis

	// OVN Northbound
	NBNAT                      = nbdb.NAT
	NBLogicalRouter            = nbdb.LogicalRouter
	NBLogicalRouterPort        = nbdb.LogicalRouterPort
	NBLogicalRouterStaticRoute = nbdb.LogicalRouterStaticRoute
	NBStaticMACBinding         = nbdb.StaticMACBinding
	NBGatewayChassis           = nbdb.GatewayChassis
)

